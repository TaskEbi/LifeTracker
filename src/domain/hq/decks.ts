/** The cards of a deck that aren't there yet, by the same question in the same deck. */
export function newCards(deck: StarterDeck, existing: { deck: string; front: string }[]): [string, string][] {
  const seen = new Set(existing.filter((c) => c.deck === deck.deck).map((c) => c.front.trim().toLowerCase()));
  return deck.cards.filter(([front]) => !seen.has(front.trim().toLowerCase()));
}
