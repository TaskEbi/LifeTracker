/**
 * Builds the Atlas section's data from the two data files of the "Atlas Drill" page it grew from:
 *
 *   node scripts/atlas-data.mjs <folder holding data.js and flags.js>
 *
 * Writes src/domain/atlas/countries.ts (don't edit it by hand), one map file per view in
 * src/features/atlas/maps/ and one flag per country in public/flags/ (flag-icons, MIT licence).
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import vm from 'node:vm';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/atlas-data.mjs <folder with data.js and flags.js>');
  process.exit(1);
}
const box = { window: {} };
vm.createContext(box);
for (const f of ['data.js', 'flags.js']) vm.runInContext(readFileSync(join(src, f), 'utf8'), box);
const { GEO, FLAGS } = box.window;

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const out = (...p) => join(root, ...p);

// flags
mkdirSync(out('public', 'flags'), { recursive: true });
for (const c of GEO.countries) {
  const uri = FLAGS[c.id];
  if (!uri?.startsWith('data:image/svg+xml;base64,')) throw new Error(`no flag for ${c.id}`);
  writeFileSync(out('public', 'flags', `${c.id}.svg`), Buffer.from(uri.slice(uri.indexOf(',') + 1), 'base64'));
}
writeFileSync(out('public', 'flags', 'LICENSE.txt'), 'Flags from flag-icons (https://github.com/lipis/flag-icons), MIT licence, copyright (c) 2013 Panayiotis Lipiridis.\n');

// maps
mkdirSync(out('src', 'features', 'atlas', 'maps'), { recursive: true });
// each map is one string in its own module (a chunk the app can keep offline, and nothing for tsc to chew on)
for (const [id, v] of Object.entries(GEO.views)) writeFileSync(out('src', 'features', 'atlas', 'maps', `${id}.ts`), `// generated by scripts/atlas-data.mjs
export default ${JSON.stringify(JSON.stringify(v))};
`);

// countries: the six nearest (by centre on the world map) are the hard wrong answers
const world = GEO.views.world.pts;
const near = (id) => {
  const [x, y] = world[id];
  return GEO.countries
    .filter((c) => c.id !== id)
    .map((c) => [c.id, Math.hypot(world[c.id][0] - x, world[c.id][1] - y)])
    .sort((a, b) => a[1] - b[1])
    .slice(0, 6)
    .map((x) => x[0]);
};
const rows = GEO.countries.map((c) => {
  const own = GEO.views[c.c];
  const p = own.pts[c.id];
  // an outline worth guessing: drawn on its continent's map and not just a ring
  const shape = !!own.shapes[c.id] && !p[2];
  return `  [${[c.id, c.n, c.cap, c.c, c.s].map((s) => JSON.stringify(s)).join(', ')}, ${world[c.id][2] ? 1 : 0}, ${shape ? 1 : 0}, ${JSON.stringify(near(c.id).join(' '))}],`;
});
writeFileSync(
  out('src', 'domain', 'atlas', 'countries.ts'),
  `/**
 * The 195 countries of the Atlas: generated by scripts/atlas-data.mjs, don't edit by hand.
 * [id (ISO alpha-2), name, capital, continent, region, tiny (a ring on the world map), has an
 * outline, the six nearest countries].
 */
export type Row = [id: string, name: string, cap: string, cont: string, sub: string, tiny: 0 | 1, shape: 0 | 1, near: string];

export const ROWS: Row[] = [
${rows.join('\n')}
];
`,
);
console.log(`${GEO.countries.length} countries, ${Object.keys(GEO.views).length} maps, ${Object.keys(FLAGS).length} flags`);
